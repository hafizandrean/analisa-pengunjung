// Deteksi Bahasa Otomatis dari Perangkat / Laptop pengguna
$browserDetectedLang = 'id';
if (!empty($_SERVER['HTTP_ACCEPT_LANGUAGE'])) {
    $pref = strtolower(substr($_SERVER['HTTP_ACCEPT_LANGUAGE'], 0, 2));
    if ($pref === 'en') {
        $browserDetectedLang = 'en';
    }
}

// Tangani perubahan bahasa cepat via query parameter ?lang=
if (isset($_GET['lang']) && in_array($_GET['lang'], ['id', 'en'])) {
    if (session_status() === PHP_SESSION_NONE) {
        session_start();
    }
    $_SESSION['lang'] = $_GET['lang'];
    saveSetting('language', $_GET['lang']);
}

